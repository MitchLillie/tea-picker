/**
 * Converts the calligraphic display characters to SVG path data, so the Mini
 * can render brush-written hanzi without bundling a web font (Shop Minis
 * disallow @font-face).
 *
 *   npx tsx scripts/build-glyphs.ts path/to/MaShanZheng-Regular.ttf
 *
 * Font: Ma Shan Zheng, © The Ma Shan Zheng Project Authors, SIL OFL 1.1
 * (licence copied to licenses/MaShanZheng-OFL.txt).
 */
import {writeFileSync} from 'node:fs'

// eslint-disable-next-line import-x/no-extraneous-dependencies
import opentype from 'opentype.js'

/** Every character drawn in calligraphy anywhere in the Mini. */
export const CHARS =
  '茶采人入品叶谱设归静' + // titles, seals, rows
  '中台日' + // traditions
  '绿黄白青红黑普花乌龙' + // classes
  '香甘醇鲜涩苦陈火' // tasting

const fontPath = process.argv[2]
if (!fontPath) throw new Error('usage: build-glyphs.ts <font.ttf>')
const font = opentype.loadSync(fontPath)
const EM = 1000
const scale = EM / font.unitsPerEm
const ascender = font.ascender * scale

const out: Record<string, {d: string; w: number}> = {}
const missing: string[] = []
for (const ch of new Set(CHARS)) {
  const g = font.charToGlyph(ch)
  if (!g || g.index === 0) {
    missing.push(ch)
    continue
  }
  const path = g.getPath(0, ascender, EM)
  out[ch] = {d: path.toPathData(0), w: Math.round((g.advanceWidth ?? font.unitsPerEm) * scale)}
}
if (missing.length) process.stderr.write(`missing glyphs: ${missing.join('')}\n`)

const body = `// Generated by scripts/build-glyphs.ts — do not edit.
// Ma Shan Zheng © The Ma Shan Zheng Project Authors, SIL Open Font License 1.1.
/* eslint-disable */
export const GLYPH_EM = ${EM}
export const GLYPHS: Record<string, {d: string; w: number}> = ${JSON.stringify(out)}
`
writeFileSync('src/scene/ink/glyphs.ts', body)
process.stdout.write(`wrote ${Object.keys(out).length} glyphs (${(body.length / 1024).toFixed(1)} KB)\n`)
